#!/usr/bin/env python3
"""Word count of the main manuscript, which Quantitative Finance asks every
submission to state.

TeXcount reads qf_paper.tex with its \\input files merged and sums running text,
headings, captions and footnotes, counting each formula as one word. It counts
no table entry, and the reference list lives in the .bbl rather than the
source, so the manuscript prints the count as excluding both. The manuscript
wraps its \\input of the file written here in %TC:ignore, so the count never
depends on the file recording it.

The count is a property of the prose. ``make pdf`` rewrites
tables/word_count.tex before compiling, and ``check_word_count_is_current``
fails on a committed count the prose has since moved.
"""
import subprocess

from paths import REPO_ROOT

MANUSCRIPT = "qf_paper.tex"
WORD_COUNT_FILE = "word_count.tex"


def manuscript_word_count() -> int:
    """TeXcount's sum over the manuscript and every file it inputs."""
    out = subprocess.run(
        ["texcount", "-merge", "-sum", "-1", MANUSCRIPT],
        cwd=REPO_ROOT, capture_output=True, text=True, check=True,
    ).stdout
    return int(out.strip())


def word_count_tex() -> str:
    count = f"{manuscript_word_count():,}".replace(",", "{,}")
    return ("% Auto-generated by code/output/word_count.py -- regenerate with: make pdf\n"
            f"\\newcommand{{\\manuscriptWordCount}}{{{count}}}\n")


if __name__ == "__main__":
    from output._formatters import write_body
    write_body(WORD_COUNT_FILE, word_count_tex())
